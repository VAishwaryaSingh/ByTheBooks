def seed():
    init_db()
    conn = get_db()

    # Clear existing data
    conn.executescript("""
        DELETE FROM standard_topics;
        DELETE FROM standards;
        DELETE FROM topics;
        DELETE FROM frameworks;
    """)
    conn.commit()

    # Insert frameworks
    framework_ids = {}
    for fw in FRAMEWORKS:
        cur = conn.execute(
            "INSERT INTO frameworks (name, code, description, governing_body, official_url, region) VALUES (?,?,?,?,?,?)",
            (fw["name"], fw["code"], fw["description"], fw["governing_body"], fw["official_url"], fw["region"]),
        )
        framework_ids[fw["code"]] = cur.lastrowid

    # Insert topics
    topic_ids = {}
    for name, desc in TOPICS:
        cur = conn.execute("INSERT INTO topics (name, description) VALUES (?,?)", (name, desc))
        topic_ids[name] = cur.lastrowid

    conn.commit()

    # Insert standards
    inserted = 0
    for std in STANDARDS:
        fw_id = framework_ids.get(std["framework"])
        if not fw_id:
            print(f"  WARNING: Unknown framework '{std['framework']}' for {std['code']}")
            continue

        cur = conn.execute(
            """INSERT INTO standards (code, title, framework_id, summary, key_points, official_url, effective_date, status)
               VALUES (?,?,?,?,?,?,?,?)""",
            (
                std["code"],
                std["title"],
                fw_id,
                std.get("summary", ""),
                std.get("key_points", ""),
                std.get("official_url", ""),
                std.get("effective_date", ""),
                std.get("status", "active"),
            ),
        )
        std_id = cur.lastrowid

        for topic_name in std.get("topics", []):
            t_id = topic_ids.get(topic_name)
            if t_id:
                conn.execute(
                    "INSERT OR IGNORE INTO standard_topics (standard_id, topic_id) VALUES (?,?)",
                    (std_id, t_id),
                )
            else:
                print(f"  WARNING: Unknown topic '{topic_name}' for {std['code']}")

        inserted += 1

    conn.commit()
    conn.close()

    print(f"\nSeeding complete:")
    print(f"  Frameworks: {len(framework_ids)}")
    print(f"  Topics: {len(topic_ids)}")
    print(f"  Standards: {inserted}")


if __name__ == "__main__":
    seed()
